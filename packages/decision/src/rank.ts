import type { CandidateClip, ClipEnergy, Direction } from '@vev/shared'

/**
 * The energy a section asks for, when the track labels its sections (spec §8.1 step 1, §9.2).
 * Free-text sections fall back to the neutral target below.
 */
export const SECTION_ENERGY = new Map<string, ClipEnergy>([
  ['break', 2],
  ['build', 3],
  ['intro', 2],
  ['outro', 2],
  ['peak', 5],
])

/** What a clip with no annotation is assumed to be worth, when the section says nothing either. */
export const NEUTRAL_ENERGY: ClipEnergy = 3

/**
 * How much an unannotated clip is trusted on energy. It is not 0: annotation is asynchronous
 * (§0 principle 2), so a freshly registered clip has no energy, and ranking it as the worst clip in
 * the library would mean a new clip could never be offered. Half a point is what a guess is worth.
 */
const UNKNOWN_ENERGY_SCORE = 0.5

export interface RankInput {
  readonly direction?: Direction
  /** The wanted energy when the caller already knows it (the decision provider answered `score`). */
  readonly energyTarget?: ClipEnergy
  /** Most recent last, as spec §8.2's `history` lists it. */
  readonly historyIds: readonly string[]
  /** The track's current section, when it has one. */
  readonly section?: string
}

/**
 * One ranked clip. `source` is `'fallback'` because every score here is generated by these rules;
 * the route replaces it with `'decision'` only for the clip the model actually chose.
 */
export interface RankedCandidate {
  readonly clip: CandidateClip
  readonly reason: string
  readonly score: number
  readonly source: 'fallback'
}

const targetEnergy = (input: RankInput): ClipEnergy => {
  const fromSection = SECTION_ENERGY.get(input.section ?? '')
  return input.energyTarget ?? input.direction?.energyTarget ?? fromSection ?? NEUTRAL_ENERGY
}

/** A short reason the UI can show; it names the signals that produced the score, never a model's words. */
const reasonFor = (
  clip: CandidateClip,
  matched: readonly string[],
  target: ClipEnergy,
  played: boolean,
): string => {
  const parts: string[] = []
  if (matched.length > 0) {
    parts.push(`tag ${matched.join('+')}`)
  }
  parts.push(clip.energy === undefined ? 'unannotated' : `energy ${clip.energy}→${target}`)
  if (!played) {
    parts.push('unplayed')
  }
  return parts.join('; ')
}

/**
 * Spec §8.1's ranking before (and without) a decision provider: a deterministic, weighted score
 * over three signals.
 *
 * - Tag match against the direction, because a steering chat's words are the most specific thing
 *   the performer has said.
 * - Energy closeness to the target, because a set has a shape.
 * - History, because a clip that has not appeared yet is worth more than one that has.
 *
 * The weights are the policy, so they are a table rather than a branch: with no direction there is
 * no tag signal, and the other two share its weight instead of the score being capped below 1.
 * A clip with no annotation still ranks — it scores neutral on energy and its missing tags simply
 * match nothing.
 */
export const rankByRules = (clips: readonly CandidateClip[], input: RankInput): RankedCandidate[] => {
  const target = targetEnergy(input)
  const wanted = input.direction?.tags ?? []
  const played = new Set(input.historyIds)

  const ranked = clips.map((clip) => {
    const tags = clip.tags ?? []
    const matched = wanted.filter((tag) => tags.includes(tag))
    const signals = [
      ...(wanted.length === 0 ? [] : [{ value: matched.length / wanted.length, weight: 0.5 }]),
      {
        value: clip.energy === undefined ? UNKNOWN_ENERGY_SCORE : 1 - Math.abs(clip.energy - target) / 4,
        weight: 0.3,
      },
      { value: played.has(clip.id) ? 0 : 1, weight: 0.2 },
    ]
    const totalWeight = signals.reduce((sum, signal) => sum + signal.weight, 0)
    const score = signals.reduce((sum, signal) => sum + signal.weight * signal.value, 0) / totalWeight

    return {
      clip,
      reason: reasonFor(clip, matched, target, played.has(clip.id)),
      score,
      source: 'fallback',
    } satisfies RankedCandidate
  })

  // Id is the tie-break so the same library and state always produce the same order: a show that
  // offered a different #1 each time it was asked the same question would look broken.
  return ranked.toSorted((a, b) => b.score - a.score || a.clip.id.localeCompare(b.clip.id))
}
